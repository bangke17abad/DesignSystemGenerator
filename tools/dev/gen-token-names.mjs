#!/usr/bin/env node
// Regenerates catalog/token-names.json by deriving all nine archetypes (Light+Dark+High-contrast, two brands, glove modality).
import { mkdtempSync, rmSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';
import { resolveLanguage } from '../resolve-language.mjs';
import { deriveTokens } from '../derive-tokens.mjs';
import { readJson, writeJson } from '../lib/tokens.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const ids = Object.keys(readJson(join(root, 'catalog', 'archetypes.json')).archetypes);
const sets = [], comp = [];
for (const a of ids) {
  const brief = { brief_schema_version: '1.5', run_mode: 'greenfield', product_name: 'T', namespace: 'T', doc_language: 'English', ui_locales: ['en-US'],
    surfaces: [{ name: 'w', input_modality: ['pointer'], surface_type: 'operational', default_theme: 'Light', density_modes: ['comfortable'] }],
    targets: { primary_web_reference: 'html-first' }, language: { mode: 'archetype', archetype: a, themes: [{ name: 'Light' }, { name: 'Dark' }], brands: [{ id: 'default' }] } };
  const { language } = resolveLanguage(brief);
  const { tokens } = deriveTokens(brief, language);
  sets.push(new Set(Object.keys(tokens.semantic)));
  comp.push(new Set(Object.keys(tokens.component)));
}
const all = new Set(sets.flatMap((s) => [...s]));
const cond = { 'font-display': 'L4 menetapkan keluarga display', 'target-min-extended': 'B3 punya modalitas glove atau in-motion', 'z-critical': 'B5 punya critical_events', 'map-land': 'B5 spatial', 'map-water': 'B5 spatial', 'map-boundary': 'B5 spatial', 'map-route': 'B5 spatial', 'elevation-3': 'L7 punya 3 tingkat' };
for (const n of all) if (!sets.every((s) => s.has(n)) && !cond[n]) cond[n] = n.startsWith('space-') ? 'langkah spasi ada di L5 archetype/brief' : 'bergantung bahasa desain';
const always = [...all].filter((n) => sets.every((s) => s.has(n)) && !cond[n]).sort();
const componentAlways = [...comp[0]].filter((n) => comp.every((s) => s.has(n))).sort();
writeJson(join(root, 'catalog', 'token-names.json'), {
  $comment: 'Generated by tools/dev/gen-token-names.mjs. Semantic token names every package produced by engine 1.8.0 contains (always), names that exist only under a condition (conditional), and the component-layer tokens every package contains (component_always). Catalog records and reference CSS may reference only always + component_always. Spacing present in every archetype: space-1, space-2, space-3, space-4, space-6, space-8, space-12. target-current is a runtime token (24 pointer, 44 coarse pointer, target-min-extended for glove/in-motion).',
  always, conditional: Object.fromEntries(Object.entries(cond).sort()), component_always: componentAlways,
});
console.log(`token-names: ${always.length} always, ${Object.keys(cond).length} conditional, ${componentAlways.length} component`);
